def draw(template, colours):
    rows = [r for r in T[template].strip('\n').split('\n')]
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in colours:
                im.putpixel((x, y), Image.new('RGB', (1, 1), colours[ch]).getpixel((0, 0)) + (255,))
    return im.resize((32, 32), Image.NEAREST)


def main(out):
    os.makedirs(out, exist_ok=True)
    for name, (tpl, col) in SPRITES.items():
        draw(tpl, col).save(os.path.join(out, name + '.png'))
    print('wrote', len(SPRITES), 'sprites to', out)


if __name__ == '__main__':
    main(sys.argv[1])
